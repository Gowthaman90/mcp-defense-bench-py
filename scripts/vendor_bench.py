"""Vendor the mcp-defense-bench corpus at a pinned commit, with a sha256 manifest.

Reads the bench repository with `git archive <commit>` only, so uncommitted edits in the bench
working tree never leak in. Writes:

  src/mcp_defense_bench/_bench/            rubric + dev + benign cases (exactly what is scored)
  src/mcp_defense_bench/_bench/MANIFEST.json
      sha256 of every vendored file, plus the held-out corpus's file hashes and counts
      (held-out fixtures themselves are NOT vendored; see docs/HELD-OUT.md)
  tests/fixtures/js-<short>/               the JS scorer's recorded dev + benign results, each
      adapter's coverage.json, and the leaderboard regenerated by bin/leaderboard.mjs; the
      parity tests compare against these byte for byte

Usage: python scripts/vendor_bench.py /path/to/mcp-defense-bench [--commit SHA]
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from mcp_defense_bench import BENCH_COMMIT, BENCH_VERSION  # noqa: E402
from mcp_defense_bench.bench import CORPUS_DIRS, scored_case_files  # noqa: E402

TOOLS = ("null-baseline", "mcp-bastion", "mcp-firewall", "pipelock")


def git(bench: Path, *args: str) -> bytes:
    return subprocess.run(["git", "-C", str(bench), *args], check=True, capture_output=True).stdout


def extract(bench: Path, commit: str, paths: list[str], dest: Path) -> None:
    data = git(bench, "archive", "--format=tar", commit, *paths)
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        for m in tar.getmembers():
            if not (m.isfile() or m.isdir()) or m.name.startswith("/") or ".." in Path(m.name).parts:
                raise SystemExit(f"refusing unexpected archive member {m.name!r}")
        tar.extractall(dest)  # noqa: S202 - members validated above


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def corpus_entry(root: Path, corpus: str) -> dict[str, object]:
    files = scored_case_files(root / CORPUS_DIRS[corpus])
    vectors = {f.parent.name for f in files}
    hashes = {f.relative_to(root).as_posix(): sha256(f) for f in files}
    digest = hashlib.sha256("".join(f"{h}  {p}\n" for p, h in hashes.items()).encode()).hexdigest()
    return {"cases": len(files), "vectorDirs": len(vectors), "digest": digest, "files": hashes}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("bench", type=Path)
    ap.add_argument("--commit", default=BENCH_COMMIT)
    a = ap.parse_args()
    commit = git(a.bench, "rev-parse", f"{a.commit}^{{commit}}").decode().strip()
    if commit != BENCH_COMMIT:
        raise SystemExit(f"commit {commit} != BENCH_COMMIT {BENCH_COMMIT}; update __init__.py first")

    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp)
        extract(
            a.bench,
            commit,
            ["rubric/crosswalk.json", *CORPUS_DIRS.values(), "results", "adapters", "bin/leaderboard.mjs", "docs/LEADERBOARD.md"],
            src,
        )
        rubric = json.loads((src / "rubric/crosswalk.json").read_text("utf8"))
        if rubric["version"] != BENCH_VERSION:
            raise SystemExit(f"rubric {rubric['version']} != BENCH_VERSION {BENCH_VERSION}")

        # 1. Package data: rubric + dev + benign scored files.
        out = REPO / "src/mcp_defense_bench/_bench"
        shutil.rmtree(out, ignore_errors=True)
        (out / "rubric").mkdir(parents=True)
        shutil.copy2(src / "rubric/crosswalk.json", out / "rubric/crosswalk.json")
        manifest: dict[str, object] = {
            "benchVersion": BENCH_VERSION,
            "benchCommit": commit,
            "rubricVersion": rubric["version"],
            "vectors": len(rubric["vectors"]),
            "generatedBy": "scripts/vendor_bench.py (git archive)",
            "rubric": {"rubric/crosswalk.json": sha256(src / "rubric/crosswalk.json")},
            "corpora": {},
        }
        corpora: dict[str, object] = {}
        for corpus in ("dev", "benign", "heldout"):
            entry = corpus_entry(src, corpus)
            entry["vendored"] = corpus != "heldout"
            corpora[corpus] = entry
            if corpus == "heldout":
                continue
            for rel in entry["files"]:  # type: ignore[union-attr]
                dst = out / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src / rel, dst)
        manifest["corpora"] = corpora
        (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", "utf8")

        # 2. Test fixtures: recorded JS outputs (dev + benign only) and the regenerated leaderboard.
        fx = REPO / f"tests/fixtures/js-{commit[:7]}"
        shutil.rmtree(fx, ignore_errors=True)
        for sub in ("results/benign", "coverage"):
            (fx / sub).mkdir(parents=True)
        for t in TOOLS:
            shutil.copy2(src / f"results/{t}.json", fx / f"results/{t}.json")
            shutil.copy2(src / f"results/benign/{t}.json", fx / f"results/benign/{t}.json")
            shutil.copy2(src / f"adapters/{t}/coverage.json", fx / f"coverage/{t}.json")
        board = subprocess.run(["node", "bin/leaderboard.mjs"], cwd=src, check=True, capture_output=True).stdout
        (fx / "LEADERBOARD.md").write_bytes(board)
        same = board == (src / "docs/LEADERBOARD.md").read_bytes()

    c = manifest["corpora"]
    print(f"vendored bench {BENCH_VERSION} @ {commit[:7]}: rubric {rubric['version']} ({manifest['vectors']} vectors)")
    for k, v in c.items():  # type: ignore[union-attr]
        print(f"  {k:8} {v['cases']:4} cases in {v['vectorDirs']:2} dirs  vendored={v['vendored']}  digest={v['digest'][:16]}")
    print(f"  regenerated leaderboard identical to committed docs/LEADERBOARD.md: {same}")


if __name__ == "__main__":
    main()
